// The static pages (public/universities, public/demo) can't import the app's CSS, so this writes one stylesheet for
// them from the same sources: the theme tokens and the site shell. Run by `npm run build`; the output is committed.
import { readFileSync, writeFileSync } from 'node:fs';
const theme = readFileSync('src/theme.css', 'utf8'), site = readFileSync('src/site/site.css', 'utf8');
writeFileSync('public/site-static.css', `/* Generated by scripts/build-static-css.mjs from src/theme.css and src/site/site.css. Don't edit by hand. */\n${theme}\n${site}`);
console.log('public/site-static.css written');
